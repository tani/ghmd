import {mkdir,readdir} from 'node:fs/promises';
import {resolve,join} from 'node:path';
const root=resolve(import.meta.dir,'..'),vendor=join(root,'vendor/cmark-gfm');
if(!['linux','darwin'].includes(process.platform))throw Error('Native build is tested on Linux; this script supports POSIX cc only.');
const sources=[];
for(const dir of ['src','extensions'])for(const name of await readdir(join(vendor,dir)))if(name.endsWith('.c')&&name!=='main.c')sources.push(join(vendor,dir,name));
await mkdir(join(root,'native'),{recursive:true});
const out=join(root,'native',`libcmark-gfm-${process.platform}-${process.arch}.${process.platform==='darwin'?'dylib':'so'}`);
const args=[process.env.CC||'cc',process.platform==='darwin'?'-dynamiclib':'-shared','-fPIC','-O2','-std=c99','-DCMARK_GFM_STATIC_DEFINE','-DCMARK_GFM_EXTENSIONS_STATIC_DEFINE',...['src','extensions','generated'].map(d=>'-I'+join(vendor,d)),...sources,join(root,'src/native-free.c'),'-o',out];
const result=Bun.spawnSync(args,{stdout:'inherit',stderr:'inherit'});
if(result.exitCode!==0)throw Error('Native build failed');console.log(out);
