/** Generate the Unicode 17 tables used by the native lowercase implementation. */
if (process.versions.unicode !== "17.0") {
  throw new Error(`Expected Unicode 17.0; this Bun uses ${process.versions.unicode}`);
}
const mappings: { cp: number; offset: number; length: number }[] = [];
const bytes: number[] = [];
const cased: [number, number][] = [];
const ignorable: [number, number][] = [];
const casedPattern = /\p{Cased}/u;
const ignorablePattern = /\p{Case_Ignorable}/u;
function addRange(ranges: [number, number][], cp: number) {
  const last = ranges.at(-1);
  if (last && last[1] + 1 === cp) last[1] = cp;
  else ranges.push([cp, cp]);
}
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  const input = String.fromCodePoint(cp);
  const lower = input.toLowerCase();
  if (lower !== input) {
    const encoded = Buffer.from(lower, "utf8");
    mappings.push({ cp, offset: bytes.length, length: encoded.length });
    bytes.push(...encoded);
  }
  if (casedPattern.test(input)) addRange(cased, cp);
  if (ignorablePattern.test(input)) addRange(ignorable, cp);
}
const hex = (value: number) => `0x${value.toString(16)}`;
const lines = [
  "/* Generated by scripts/generate-unicode-lower.ts using Unicode 17.0. */",
  "typedef struct { uint32_t cp, offset; uint8_t length; } gfm_lower_mapping;",
  "typedef struct { uint32_t first, last; } gfm_unicode_range;",
  "static const uint8_t gfm_lower_bytes[] = {",
];
for (let i = 0; i < bytes.length; i += 20)
  lines.push(
    `  ${bytes
      .slice(i, i + 20)
      .map(hex)
      .join(", ")},`,
  );
lines.push("};", "static const gfm_lower_mapping gfm_lower_mappings[] = {");
for (const mapping of mappings)
  lines.push(`  {${hex(mapping.cp)}, ${mapping.offset}, ${mapping.length}},`);
lines.push("};");
for (const [name, ranges] of [
  ["gfm_cased_ranges", cased],
  ["gfm_ignorable_ranges", ignorable],
] as const) {
  lines.push(`static const gfm_unicode_range ${name}[] = {`);
  for (const [first, last] of ranges) lines.push(`  {${hex(first)}, ${hex(last)}},`);
  lines.push("};");
}
await Bun.write(
  new URL("../src/quirks/cmark/unicode-lower-data.h", import.meta.url),
  lines.join("\n") + "\n",
);
console.log(
  `${mappings.length} mappings, ${cased.length} cased and ${ignorable.length} case-ignorable ranges`,
);
